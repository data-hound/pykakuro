#!/usr/bin/env python3
"""Masks of v2 test puzzle_ids that must be (re)run through an API to obtain a COMPLETE 5 000-puzzle result per size.
For each API model and size we mark every v2 test puzzle:
  has_output        an existing response was matched to this exact puzzle (old 11x11 runs only; 9x9 and 15x15 were never run)
  complete_grid     that response contained a full answer grid (False => truncated/unparseable; a rerun with a larger token budget is advisable)
  need_rerun_missing  no output at all -> MUST be run
  need_rerun_all      missing OR output unusable (no complete grid) -> run these for a complete, non-truncated 5 000 set
  need_rerun_corrected_legend  ALL puzzles: every existing API output used the swapped (d,r) clue legend, so a clean, comparable result needs the whole set rerun with the corrected prompt
Output (shared storage, i.e. on DCC): kakuro-craze/benchmark/api_rerun_masks/<model>__grid<N>_test.csv, plus all_masks.parquet and README.md.
No API call is made by this script."""
import glob, os, sys
import pandas as pd
here = os.path.dirname(os.path.abspath(__file__))
_ROOT = "/hpc/group/tdunn/asabath/ece790_diffusion" if os.path.isdir("/hpc/group/tdunn/asabath/ece790_diffusion") else "/home/as1296/dcc_mount/ece790_diffusion"
D = _ROOT + "/Project/ar-diffusion-2d/data/"; OUT = _ROOT + "/Project/kakuro-craze/benchmark/api_rerun_masks/"; os.makedirs(OUT, exist_ok=True)
v1 = pd.read_parquet(f"{D}kakuro_kraze/grid11/test.parquet", columns=["puzzle"]).reset_index().rename(columns={"index": "idx"}); v1["pk"] = v1.puzzle.str.strip()
per = pd.read_parquet(f"{here}/out/rescored_all_models_per_puzzle.parquet")
API = {"gpt-5-mini": "gpt-5-mini (batch, 11x11)", "gpt-5-nano": "gpt-5-nano (batch)", "claude-sonnet-4-5": "Claude Sonnet 4.5 (batch)"}
allm = []
for n in (9, 11, 15):
    v2 = pd.read_parquet(f"{D}kakuro_kraze_v2/grid{n}/test.parquet", columns=["puzzle_id", "puzzle", "topped_up", "legacy_split", "difficulty_tertile"]); v2["pk"] = v2.puzzle.str.strip()
    for short, run in API.items():
        m = v2[["puzzle_id", "topped_up", "legacy_split", "difficulty_tertile", "pk"]].copy()
        if n == 11:
            r = per[per.run == run].merge(v1[["idx", "pk"]], on="idx")[["pk", "parsed"]]
            m = m.merge(r, on="pk", how="left"); m["has_output"] = m.parsed.notna(); m["complete_grid"] = m.parsed.fillna(False).astype(bool)
        else:
            m["has_output"] = False; m["complete_grid"] = False
        m["need_rerun_missing"] = ~m.has_output; m["need_rerun_all"] = ~(m.has_output & m.complete_grid)
        m["need_rerun_corrected_legend"] = True      # every existing API output used the swapped (d,r) clue legend (see REBUTTAL_NUMBERS.md)
        m = m.drop(columns=[c for c in ("pk", "parsed") if c in m]).assign(model=short, grid=n)
        m.to_csv(f"{OUT}{short}__grid{n}_test.csv", index=False); allm.append(m)
a = pd.concat(allm); a.to_parquet(OUT + "all_masks.parquet")
s = a.groupby(["model", "grid"]).agg(total=("puzzle_id", "size"), have_output=("has_output", "sum"), complete=("complete_grid", "sum"), rerun_missing=("need_rerun_missing", "sum"), rerun_all=("need_rerun_all", "sum")).reset_index()
print(s.to_string(index=False))
open(OUT + "README.md", "w").write("""# API rerun masks (v2 test sets)
Generated by `pykakuro/analysis/16_make_api_rerun_masks.py` on 2026-10-09. No API calls were made.
One CSV per model x grid: `puzzle_id` (v2), `topped_up`, `legacy_split`, `difficulty_tertile`, `has_output`, `complete_grid`, `need_rerun_missing`, `need_rerun_all`, `need_rerun_corrected_legend`.
- `need_rerun_missing`: puzzles with no existing response (all of 9x9 and 15x15; for 11x11 the 787 new puzzles plus any whose old batch request errored).
- `need_rerun_all`: additionally puzzles whose old response had no complete answer grid (truncated at the old token limit); rerun with a larger budget.
**WARNING:** all existing API outputs were produced with a system prompt that mislabelled the clue order as (down, right) (the data is (right, down)); see `kakuro-craze/REBUTTAL_NUMBERS.md` and `Project/KNOWN_CAVEATS.md` (the originals may live on workstation 10.237.192.106; verify first). `need_rerun_missing` / `need_rerun_all` therefore only complete the set under that flawed prompt; for clean results use `need_rerun_corrected_legend` (everything).
- Existing 11x11 outputs are matched by exact puzzle text, so they are reusable only for puzzles marked `has_output` (and `complete_grid` for scoring).
Summary table: `summary.csv`.
""")
s.to_csv(OUT + "summary.csv", index=False)
