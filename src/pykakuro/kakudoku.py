"""
    Code to generate partially filled Kakuro boards, combining Kakuro and Sudoku problem settings.
    Boards are generated by progressive filling of the Kakuro boards, where easier boards have more cells filled than difficult videos.
"""

import random
import json
import hashlib
import pandas as pd
from datasets import load_dataset
from pathlib import Path
import pyarrow as pa
import pyarrow.parquet as pq
import ast


class ProgressiveKakuroGenerator:

    def __init__(self, puzzle_grid, solution_grid):

        self.puzzle = puzzle_grid
        self.solution = solution_grid
        self.n = len(puzzle_grid)

        assert isinstance(puzzle_grid, list), "Expected puzzle_grid to be a list of lists"
        print(f"Length of puzzle grid = {self.n}")

        self.play_cells = [
            (r,c)
            for r in range(self.n)
            for c in range(self.n)
            if puzzle_grid[r][c] == 1
        ]

    def remove_cells(self, remove_count):

        puzzle = [[self.solution[r][c] if (r,c) in self.play_cells else self.puzzle[r][c]
                   for c in range(self.n)] for r in range(self.n)]

        cells = self.play_cells[:]
        random.shuffle(cells)

        removed = cells[:remove_count]

        for r,c in removed:
            puzzle[r][c] = "."

        remaining = removed[:]

        return puzzle, remaining


    def fill_cells(self, puzzle_board, available_cells, fill_count):

        puzzle = [row[:] for row in puzzle_board]

        cells = available_cells[:]
        random.shuffle(cells)

        used = cells[:fill_count]
        remaining = cells[fill_count:]

        for r,c in used:
            puzzle[r][c] = self.solution[r][c]

        return puzzle, remaining

class ParquetBatchWriter:

    def __init__(self, path, schema=None):

        self.path = path
        self.writer = None
        self.schema = schema

    def write_batch(self, rows):

        table = pa.Table.from_pylist(rows)

        if self.writer is None:
            self.schema = table.schema
            self.writer = pq.ParquetWriter(self.path, self.schema)

        self.writer.write_table(table)

    def close(self):

        if self.writer:
            self.writer.close()


def board_hash(board):
    flat = ''.join(str(x) for row in board for x in row)
    return hashlib.sha1(flat.encode()).hexdigest()[:16]

def solution_hash(board):
    return ''.join(str(x) for row in board for x in row)

def make_board_id(h,size,diff):
    return f"K{size}_{diff}_{h}"

def difficulty_removals(total_cells):

    return {
        "expert": int(total_cells),
        "hard": int(total_cells*0.70),
        "medium": int(total_cells*0.55),
        "easy": int(total_cells*0.40)
    }


def generate_progressive_puzzles(gen):

    total = len(gen.play_cells)
    expert_board = gen.puzzle

    remove_map = difficulty_removals(total)

    hard_remove = remove_map["hard"]

    hard_board, removed_cells = gen.remove_cells(hard_remove)

    medium_fill = remove_map["hard"] - remove_map["medium"]

    medium_board, removed_cells = gen.fill_cells(
        hard_board,
        removed_cells,
        medium_fill
    )

    easy_fill = remove_map["medium"] - remove_map["easy"]

    easy_board, removed_cells = gen.fill_cells(
        medium_board,
        removed_cells,
        easy_fill
    )

    return {
        "expert": expert_board,
        "hard": hard_board,
        "medium": medium_board,
        "easy": easy_board
    }, remove_map

def parse_grid(s):
    s = s.strip()

    # wrap rows if the dataset omitted the outer list
    if not s.startswith("[["):
        s = "[" + s.replace("\n", ",") + "]"

    grid = ast.literal_eval(s)

    return [list(row) for row in grid]

def generate_kakuro_dataset(target_boards):

    ds = load_dataset("Apaxdor/Kakuro_mania")["train"]

    ds = ds.filter(lambda x: x["is_exclusive"] == True)

    dataset = []

    seen_root = set()

    for sample in ds:

        puzzle = sample["puzzle"]
        solution = sample["solution"]

        gen = ProgressiveKakuroGenerator(puzzle, solution)

        puzzles, remove_map = generate_progressive_puzzles(gen)

        root_hash = board_hash(puzzles["hard"])

        if root_hash in seen_root:
            continue

        seen_root.add(root_hash)

        shash = solution_hash(solution)

        for diff,board in puzzles.items():

            pid = make_board_id(root_hash, len(puzzle), diff)

            dataset.append({
                "board_id": pid,
                "root_hash": root_hash,
                "solution_id": shash,
                "size": len(puzzle),
                "difficulty": diff,
                "missing_cells": remove_map[diff],
                "puzzle_grid": json.dumps(board),
                "solution_grid": json.dumps(solution)
            })

        if len(dataset) >= target_boards:
            break

    return dataset

